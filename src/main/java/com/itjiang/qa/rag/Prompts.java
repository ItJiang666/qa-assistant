package com.itjiang.qa.rag;

/**
 * 提示词常量。
 *
 * <p><b>为什么系统提示词放在这里，而不是写在 {@code QaAssistant} 的注解上？</b>
 *
 * <p>因为实测发现 {@code @SystemMessage} <b>根本送不到模型</b>：
 * LangChain4j 的 {@code ChatMemory} 一旦配置了 {@code chatMemoryStore}，
 * 消息就以 store 为准 —— 框架把 system 消息 {@code add} 进内存后调用
 * {@code updateMessages}，而我们为了让对话历史只由 {@code ChatService} 唯一落库，
 * 那个方法是<b>刻意留空</b>的；紧接着框架又从 {@code getMessages} 重新读取，
 * 于是刚加进去的 system 消息当场丢失。
 *
 * <p>实测证据：打开请求日志后，发往 Ollama 的 {@code messages} 数组里
 * <b>只有一条 user 消息</b>，system 段完全不存在 —— 铁律、长期记忆全都没进 Prompt。
 *
 * <p>因此改为由 {@link com.itjiang.qa.memory.JdbcChatMemoryStore} 在读取历史时
 * <b>把系统提示词拼在最前面</b>：那才是唯一可靠、每次都经过的路径。
 *
 * <p>⚠️ 这里的内容<b>不能含模板变量</b>：它由 store 直接构造，没有任何插值环节。
 * 长期记忆改为注入到用户消息里（见 {@code ChatService}）。
 *
 * @author Jiang
 */
public final class Prompts {

    /**
     * 系统提示词。
     *
     * <p><b>这份提示词直接决定回答质量，改动前请先想清楚。</b>
     * 几条铁律分别对应几类失败模式：
     * <ol>
     *   <li>用模型自身的知识回答 → 用户拿到一个"看起来对"但没出处的答案</li>
     *   <li>资料里没有就硬编 → 编造的内部规定会被当成真的执行</li>
     *   <li>编造数字与流程 → 知识库问答里危害最大的一类幻觉</li>
     *   <li>不给出处 → 用户无法核对，错误答案会被无声地信任</li>
     *   <li>不遵守用户偏好 → 长期记忆写了等于白写</li>
     * </ol>
     *
     * <p>第 8 条（默认从简）不是幻觉防线，而是<b>延迟防线</b>：本地模型实测约 60 token/s，
     * 500 字的回答光生成就要 8 秒，200 字约 3 秒；把"默认简短、要详细再要"写进提示词，
     * 比事后再去优化链路更直接。它与第 5 条（【偏好】优先）刻意留了让路条款。
     *
     * <p>第 2 条写成"下方没有出现任何资料"是刻意的：检索用 minScore 过滤，
     * 当没有任何片段达标时注入的是空资料占位符，模型需要一个明确的判断依据。
     */
    public static final String SYSTEM = """
            你是一个知识库问答助手，服务于一个内部知识库。

            【铁律】
            1. 只使用下方提供的资料回答，不得使用你自己的知识补充
            2. 如果下方没有出现任何资料，或资料中没有相关内容，
               一律回答"现有资料中未找到相关信息"，不要尝试用自己的知识作答
            3. 严禁编造任何规定、数字、流程
            4. 引用具体内容时注明来源文档名
            5. 用户消息里若出现【偏好】，必须在本次回答中严格遵守（长度、语气、格式都算），
               它代表用户对回答方式的明确要求，优先级高于你的默认习惯
            6. 【偏好】不能当作事实依据；与资料冲突时一律以资料为准
            7. 用中文回答；结论放前面，步骤用序号
            8. 默认从简：回答控制在 200 字以内，能一段说清就不分点、不铺垫、不复述问题；
               只有用户明确要求"详细说明/展开/举例"，或资料本身是必须逐条照搬的清单时才放宽
               （与第 5 条冲突时，以【偏好】为准）

            【特别注意】
            你的知识库是公司内部资料，范围很窄。对于常识类问题
            （例如地理、历史、通用技术），知识库里几乎一定没有资料 ——
            这类问题同样必须回答"现有资料中未找到相关信息"，
            而不是用你训练时学到的知识来回答。
            """;

    /**
     * 工具类，禁止实例化。
     */
    private Prompts() {
    }
}

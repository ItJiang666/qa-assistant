package com.itjiang.qa.common;

/**
 * 空回答判定：把"模型没说出任何东西"的回答识别出来。
 *
 * <h2>为什么需要它</h2>
 * <p>实测出现过两次回答内容为 {@code []} 的情况（一次云端、一次本地，40 多次提问中 2 次，
 * 至今未复现）。不管根因是什么，<b>空回答永远不是合法结果</b>：
 * 用户看到两个方括号只会困惑，而且它会被当成正式回答写进对话历史，污染后续上下文。
 *
 * <h2>为什么不是简单的 {@code isBlank}</h2>
 * <p>因为模型的"空"有几种形态，都见过或都可能出现：
 * <pre>
 *   （空字符串）      —— 直接没吐字
 *   []               —— 吐了个空 JSON 数组（实测发生）
 *   {}   ""   ''     —— 空对象 / 空引号包裹
 *   。 ， ！          —— 只有标点，同样没有信息量
 * </pre>
 * 所以判定规则是：<b>去掉空白、成对符号与标点之后，还剩不剩得下东西</b>。
 * 只要剩不下，就视为空回答。
 *
 * <h2>为什么可能误杀</h2>
 * <p>理论上模型可以合法地回答一个符号（例如"上面那句话里用了什么括号？"→"[]"）。
 * 这种场景在本项目的定位下不成立：它是知识库问答助手，不是字符游戏助手，
 * 而"把空回答当成功"的代价（用户困惑 + 历史被污染）远大于"极少数符号类问题被要求重试"。
 *
 * @author Jiang
 */
public final class AnswerGuard {

    /**
     * 视为"没有信息量"的字符集合。
     *
     * <p>包含：空白、成对的结构符号、中英文常见标点。
     */
    private static final String NON_CONTENT_CHARS =
            " \t\r\n\u3000"                    // 空白（含全角空格）
                    + "[]{}()<>"                       // 成对结构符号
                    + "\"'`“”‘’「」『』【】"           // 引号类
                    + ".,;:!?、，。；：！？…—-~*#|/\\+=_" // 标点与分隔符
                    + "0123456789";                    // 纯数字（如模型吐出 "0"，同样无信息量）

    /**
     * 工具类，禁止实例化。
     */
    private AnswerGuard() {
    }

    /**
     * 判断回答是否为空。
     *
     * @param answer 模型回答，可为 {@code null}
     * @return 空回答（无任何实质内容）返回 {@code true}
     */
    public static boolean isEmpty(String answer) {
        if (answer == null) {
            return true;
        }
        for (int i = 0; i < answer.length(); i++) {
            char ch = answer.charAt(i);
            if (NON_CONTENT_CHARS.indexOf(ch) < 0) {
                return false;
            }
        }
        return true;
    }

    /**
     * 给用户看的替代文案。
     *
     * <p>刻意不写"系统错误"：这不是系统崩溃，而是模型这次没有产出可用内容，
     * 重试往往就好了。同时告诉用户"已记录"，让他知道这个现象会被跟进，
     * 而不是又一个没人管的偶发问题。
     *
     * @return 提示文案
     */
    public static String emptyAnswerMessage() {
        return "模型这次没有返回任何内容（已记录该异常），请重试一次；"
                + "若反复出现，请在「模型来源」里换一个模型试试。";
    }
}
